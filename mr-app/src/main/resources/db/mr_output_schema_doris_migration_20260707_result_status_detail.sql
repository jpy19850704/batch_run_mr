-- =====================================================================
-- 结果表状态与 IMA 资本明细字段迁移
-- 适用场景：
-- 1. 情景结果写入口径改为 STATUS + LOGS_JSON。
-- 2. IMA 情景 PnL 中间表增加 STATUS + LOGS_JSON。
-- 3. IMA 资本计算明细字段从 RESULT_JSON 调整为 DETAIL_JSON。
--
-- 注意：
-- 1. 本脚本不删除历史 RESULT_JSON / ERROR / DETAIL 列。
-- 2. 旧列待下游查询全部切换后，再单独执行物理清理。
-- 3. 本脚本按一次性迁移使用，重复执行前需先检查列是否已存在。
-- 4. 本脚本用于旧库迁移，新库初始化直接执行 mr_output_schema_doris.sql。
-- =====================================================================

ALTER TABLE TB_OUT_TRADE_SCENARIO_RESULT_DETAIL
ADD COLUMN STATUS VARCHAR(16) COMMENT '情景结果状态：SUCCESS / ERROR' AFTER PNL;

ALTER TABLE TB_OUT_TRADE_SCENARIO_RESULT_DETAIL
ADD COLUMN LOGS_JSON TEXT COMMENT '情景结果日志JSON' AFTER STATUS;

ALTER TABLE TB_OUT_TRADE_SCENARIO_VAR_RESULT_DETAIL
ADD COLUMN STATUS VARCHAR(16) COMMENT '情景VaR结果状态：SUCCESS / ERROR' AFTER ALL_PNL;

ALTER TABLE TB_OUT_TRADE_SCENARIO_VAR_RESULT_DETAIL
ADD COLUMN LOGS_JSON TEXT COMMENT '情景VaR结果日志JSON' AFTER STATUS;

ALTER TABLE TB_OUT_IMA_MODELLABLE_SCENARIO_PNL
ADD COLUMN STATUS VARCHAR(16) COMMENT '情景PnL状态：SUCCESS / ERROR' AFTER ALL_PNL;

ALTER TABLE TB_OUT_IMA_MODELLABLE_SCENARIO_PNL
ADD COLUMN LOGS_JSON TEXT COMMENT '情景PnL日志JSON' AFTER STATUS;

ALTER TABLE TB_OUT_IMA_NMRF_SCENARIO_PNL
ADD COLUMN STATUS VARCHAR(16) COMMENT '情景PnL状态：SUCCESS / ERROR' AFTER PNL;

ALTER TABLE TB_OUT_IMA_NMRF_SCENARIO_PNL
ADD COLUMN LOGS_JSON TEXT COMMENT '情景PnL日志JSON' AFTER STATUS;

ALTER TABLE TB_OUT_IMA_CAPITAL_RESULT
ADD COLUMN DETAIL_JSON TEXT COMMENT '资本计算明细JSON' AFTER IMCC_COMM;

UPDATE TB_OUT_IMA_CAPITAL_RESULT
SET DETAIL_JSON = RESULT_JSON
WHERE DETAIL_JSON IS NULL
  AND RESULT_JSON IS NOT NULL;

UPDATE TB_OUT_TRADE_SCENARIO_RESULT_DETAIL
SET STATUS = 'SUCCESS'
WHERE STATUS IS NULL;

UPDATE TB_OUT_TRADE_SCENARIO_VAR_RESULT_DETAIL
SET STATUS = 'SUCCESS'
WHERE STATUS IS NULL;

UPDATE TB_OUT_IMA_MODELLABLE_SCENARIO_PNL
SET STATUS = 'SUCCESS'
WHERE STATUS IS NULL;

UPDATE TB_OUT_IMA_NMRF_SCENARIO_PNL
SET STATUS = 'SUCCESS'
WHERE STATUS IS NULL;
